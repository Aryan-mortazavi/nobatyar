const catalogues: Record<Locale, Dictionary> = { fa, en };

export function getDictionary(locale: Locale): Dictionary {
  return catalogues[locale] ?? catalogues.fa;
}

/** Localised field: prefer the requested locale, fall back to the base value. */
export function pick(
  locale: Locale,
  base: string | null | undefined,
  localized: string | null | undefined,
): string {
  if (locale === "fa" && localized) return localized;
  return base ?? localized ?? "";
}
